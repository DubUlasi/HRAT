// action can be exercised immediately, without the Registry Officer / Department UIs existing yet.
// In place of those roles, a couple of fields below (complaintNumber, admissibility.decision) are
// pre-filled to stand in for work "already done" by an officer.

function activity(message, actor, timestamp) {
  return { id: `${actor}-${timestamp}-${message.slice(0, 8)}`, message, actor, timestamp };
}

